//
//  main.swift
//  basic-recipe-catalog
//
//  Writes BASICRecipeCatalog.swift from the recipe folders, so the recipes
//  are compiled into every tool and none of them has a bundle to find.
//
//      swift run basic-recipe-catalog            (in Code/BASICRecipes)
//      swift run basic-recipe-catalog <Recipes> <BASICRecipeCatalog.swift>
//
//  It reads the folders with the same loader the tools use for a user's
//  recipes, so a folder means the same thing either way. The tests fail when
//  the catalog and the folders differ: run this after changing a recipe.
//

import BASICRecipes
import Foundation

let arguments = CommandLine.arguments.dropFirst()
let recipesFolder = URL(fileURLWithPath: arguments.first ?? "Recipes", isDirectory: true)
let output = URL(fileURLWithPath: arguments.dropFirst().first ?? "Sources/BASICRecipes/BASICRecipeCatalog.swift")

/// `text` as a raw multi-line string literal that is exactly `text`: the
/// newlines after the opening quotes and before the closing ones are not
/// part of a multi-line literal, and enough `#`s keep its own quotes and
/// backslashes literal.
func literal(_ text: String, indent: String) -> String {
    var hashes = "#"
    while text.contains("\"\"\"" + hashes) || text.contains("\\" + hashes) {
        hashes += "#"
    }
    // A multi-line literal's lines are indented as deep as its closing
    // quotes; indenting each line keeps the source readable.
    let body = text.split(separator: "\n", omittingEmptySubsequences: false)
        .map { $0.isEmpty ? "" : indent + $0 }
        .joined(separator: "\n")
    return "\(hashes)\"\"\"\n\(body)\n\(indent)\"\"\"\(hashes)"
}

guard FileManager.default.fileExists(atPath: recipesFolder.appendingPathComponent("_shared").path) else {
    FileHandle.standardError.write(Data("""
    basic-recipe-catalog: no recipe folders at \(recipesFolder.path).
    Run it in Code/BASICRecipes, or name the Recipes folder and the catalog file:
        swift run basic-recipe-catalog <Recipes> <BASICRecipeCatalog.swift>

    """.utf8))
    exit(2)
}

do {
    let recipes = try BASICRecipes.load(folder: recipesFolder)
    var source = """
    //
    //  BASICRecipeCatalog.swift
    //  BASICRecipes
    //
    //  GENERATED by `swift run basic-recipe-catalog` from Recipes/. Do not
    //  edit: change the recipe folders and run it again.
    //

    // swiftlint:disable file_length

    enum BASICRecipeCatalog {
        static let recipes: [BASICRecipe] = [

    """
    for recipe in recipes {
        let json = try String(contentsOf: recipesFolder.appendingPathComponent(folderName(of: recipe)).appendingPathComponent("recipe.json"), encoding: .utf8)
        source += "        recipe(\n"
        source += "            json: \(literal(json, indent: "            ")),\n"
        source += "            files: [\n"
        for file in recipe.files {
            source += "                (\"\(file.path)\", \(literal(file.contents, indent: "                "))),\n"
        }
        source += "            ]\n"
        source += "        ),\n"
    }
    source += """
        ]

        /// A recipe from its `recipe.json` and files. The JSON was read from a
        /// folder when this file was written, and the tests read it again.
        private static func recipe(json: String, files: [(String, String)]) -> BASICRecipe {
            do {
                return try BASICRecipe(json: json, files: files.map { BASICRecipe.File(path: $0.0, contents: $0.1) })
            } catch {
                fatalError("A built-in recipe's recipe.json does not read: \\(error)")
            }
        }
    }

    """
    try source.write(to: output, atomically: true, encoding: .utf8)
    print("wrote \(recipes.count) recipes to \(output.path)")
} catch {
    FileHandle.standardError.write(Data("basic-recipe-catalog: \(error)\n".utf8))
    exit(1)
}

/// The folder a loaded recipe came from: the one whose `recipe.json` has its
/// identifier.
func folderName(of recipe: BASICRecipe) -> String {
    let folders = (try? FileManager.default.contentsOfDirectory(atPath: recipesFolder.path)) ?? []
    for folder in folders.sorted() {
        let json = recipesFolder.appendingPathComponent(folder).appendingPathComponent("recipe.json")
        guard let data = try? Data(contentsOf: json),
              let definition = try? JSONDecoder().decode(BASICRecipe.Definition.self, from: data),
              definition.identifier == recipe.id else { continue }
        return folder
    }
    return recipe.id
}
