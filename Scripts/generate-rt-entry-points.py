#!/usr/bin/env python3
# generate-rt-entry-points.py — the WebAssembly runner's table of BASICRT's
# entry points (BASIC-45).
#
# A module compiled to WebAssembly imports the runtime by name, and every value
# crossing into JavaScript is a number. This writes, for each `@_cdecl`
# function in BASICRT, a Swift closure that takes those numbers, calls the
# function with its real types, and answers its result as a number. A test
# (RTEntryPointsTests) fails when the table is older than the runtime: run
# this again after adding or changing an entry point.
#
# Usage: Code/Scripts/generate-rt-entry-points.py
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
COMPILER = os.path.join(HERE, "..", "BASICCompiler")
SOURCES = sorted(glob.glob(os.path.join(COMPILER, "Sources", "BASICRT", "*.swift")))
OUTPUT = os.path.join(COMPILER, "Sources", "BASICWasmRunner", "RTEntryPoints.swift")

# Parameters that are a function the runtime will call: the runner hands the
# runtime a native trampoline for the module's table slot. Name -> {index: shape}.
CALLBACKS = {
    "basic_rt_handler_register": {1: "ptrVoid"},
    "basic_rt_event_register": {2: "ptrVoid"},
    "basic_rt_timer_on": {2: "ptrVoid"},
    "basic_rt_task_launch": {1: "ptrPtr"},
    "basic_rt_tasks_install": {0: "voidPtr", 1: "ptrVoid"},
}

def split_parameters(text):
    parts, depth, current = [], 0, ""
    for ch in text:
        if ch in "<([": depth += 1
        if ch in ">)]": depth -= 1
        if ch == "," and depth == 0:
            parts.append(current); current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current)
    return [p.split(":", 1)[1].strip() if ":" in p else p.strip() for p in parts]

def argument(type_, index, function):
    a = f"a[{index}]"
    shape = CALLBACKS.get(function, {}).get(index)
    if shape:
        return f"WasmCallbacks.trampoline(.{shape}, forTableIndex: {a})"
    if type_ == "Double": return a
    if type_ in ("Int", "Int64", "Int32", "UInt8", "UInt64"): return f"{type_}({a})"
    if type_ == "Bool": return f"{a} != 0"
    # A pointer the Swift signature calls non-optional is passed as the bits
    # the module gave, null included, exactly as a native call passes it: a
    # call with no arguments may hand over a null argument array, which the
    # callee never reads. Unwrapping would trap where native code does not;
    # the optional and the pointer have one layout, so the cast is the bits.
    if type_ == "UnsafeMutableRawPointer?": return f"UnsafeMutableRawPointer(bitPattern: UInt({a}))"
    if type_ == "UnsafeMutableRawPointer": return f"unsafeBitCast(UnsafeMutableRawPointer(bitPattern: UInt({a})), to: UnsafeMutableRawPointer.self)"
    if type_ == "UnsafeRawPointer?": return f"UnsafeRawPointer(bitPattern: UInt({a}))"
    if type_ == "UnsafeRawPointer": return f"unsafeBitCast(UnsafeRawPointer(bitPattern: UInt({a})), to: UnsafeRawPointer.self)"
    m = re.fullmatch(r"(UnsafePointer|UnsafeMutablePointer)<(.+)>(\??)", type_)
    if m:
        kind, element, optional = m.groups()
        if optional:
            return f"{kind}<{element}>(OpaquePointer(bitPattern: UInt({a})))"
        return f"unsafeBitCast({kind}<{element}>(bitPattern: UInt({a})), to: {kind}<{element}>.self)"
    sys.exit(f"generate-rt-entry-points: {function} takes a {type_}, which this script does not know")

def result(type_, call):
    if type_ in ("Void", "()"): return f"{call}; return 0"
    if type_ == "Never": return call
    if type_ == "Double": return call
    if type_ == "Bool": return f"{call} ? 1 : 0"
    if type_ in ("Int", "Int64", "Int32"): return f"Double({call})"
    if type_.endswith("?") and "Pointer" in type_: return f"({call}).map {{ Double(UInt(bitPattern: $0)) }} ?? 0"
    if "Pointer" in type_: return f"Double(UInt(bitPattern: {call}))"
    sys.exit(f"generate-rt-entry-points: a result of type {type_}, which this script does not know")

entries = []
for path in SOURCES:
    text = open(path).read()
    for m in re.finditer(r'@_cdecl\("([^"]+)"\)\s*\n\s*public func (\w+)\((.*?)\)\s*(?:->\s*([^{]+?))?\s*\{', text, re.S):
        name, swift_name, params, returns = m.group(1), m.group(2), m.group(3), (m.group(4) or "Void").strip()
        types = split_parameters(params) if params.strip() else []
        arguments = ", ".join(argument(t, i, name) for i, t in enumerate(types))
        entries.append((name, f"{swift_name}({arguments})", returns, len(types)))

entries.sort()
lines = [
    "// Generated by Scripts/generate-rt-entry-points.py from BASICRT's @_cdecl",
    "// functions. Do not edit; run the script again after changing the runtime.",
    "",
    "import BASICRT",
    "import Foundation",
    "",
    "/// One runtime entry point: its arity, and a call taking every argument as a",
    "/// number and answering the result as one. Public, because a framework map",
    "/// (BASIC-45) brings entries of its own for a host to hand the runner.",
    "public struct RTEntryPoint: Sendable {",
    "    public let arity: Int",
    "    public let call: @Sendable (UnsafePointer<Double>) -> Double",
    "    public init(arity: Int, call: @escaping @Sendable (UnsafePointer<Double>) -> Double) {",
    "        self.arity = arity",
    "        self.call = call",
    "    }",
    "}",
    "",
    "/// An entry a host supplies, as the runtime's are shaped.",
    "public typealias WasmEntryPoint = RTEntryPoint",
    "",
    "enum RTEntryPoints {",
    f"    /// {len(entries)} entry points, by name.",
    "    static let table: [String: RTEntryPoint] = [",
]
for name, call, returns, arity in entries:
    lines.append(f'        "{name}": RTEntryPoint(arity: {arity}) {{ a in {result(returns, call)} }},')
lines += ["    ]", "}", ""]
os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
open(OUTPUT, "w").write("\n".join(lines))
print(f"generate-rt-entry-points: {len(entries)} entry points -> {os.path.relpath(OUTPUT)}")
